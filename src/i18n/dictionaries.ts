export type Dictionary = typeof fa;
export const dictionaries: Record<Locale, Dictionary> = { fa, en };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale] ?? dictionaries[defaultLocale];
}

/** Replace {name}-style placeholders. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";

/** Localise digits: Persian digits for fa, unchanged for en. */
export function num(value: number | string, locale: Locale): string {
  const s = String(value);
  return locale === "fa" ? s.replace(/\d/g, (d) => FA_DIGITS[Number(d)]) : s;
}
